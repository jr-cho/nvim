-- mix(fg, bg, pct): pct% of bg + rest fg (same as base46 colors.mix)
local function mix(fg, bg, pct)
  local function rgb(h) return tonumber(h:sub(2, 3), 16), tonumber(h:sub(4, 5), 16), tonumber(h:sub(6, 7), 16) end
  local fr, fg_, fb = rgb(fg)
  local br, bg_, bb = rgb(bg)
  local t = pct / 100
  return string.format("#%02x%02x%02x", fr * (1 - t) + br * t + 0.5, fg_ * (1 - t) + bg_ * t + 0.5, fb * (1 - t) + bb * t + 0.5)
end

